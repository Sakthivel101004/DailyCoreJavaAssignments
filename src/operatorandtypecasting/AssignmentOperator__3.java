package operatorandtypecasting;
/*
 * Assignment Operator:
 *  Write a program using +=, -=, *=, and /= operators on a variable.
 * */

public class AssignmentOperator__3 {
	
	void assign(int num) {
		System.out.println("Number: "+num);
		num+=5;
		System.out.println("addition: "+num);
		num-=5;
		System.out.println("subtraction: "+num);
		num*=5;
		System.out.println("multiplication: "+num);
		num/=5;
		System.out.println("division: "+num);
		
		
		
		
		
		
		
		
		
	}

}
